def seed_places(db) -> None:
    from app.models import Place, PlaceCategory

    for cid, name, icon, sort in CATEGORIES:
        cat = db.get(PlaceCategory, cid) or PlaceCategory(id=cid)
        cat.name, cat.icon, cat.sort = name, icon, sort
        db.merge(cat)
    for pid, name, city, category, summary, why, fact in PLACES:
        place = db.get(Place, pid) or Place(id=pid)
        place.name, place.city, place.category_id = name, city, category
        place.summary, place.why_visit, place.fact = summary, why, fact
        place.photo_query = PHOTO_QUERIES.get(pid, "")
        db.merge(place)
    db.commit()
